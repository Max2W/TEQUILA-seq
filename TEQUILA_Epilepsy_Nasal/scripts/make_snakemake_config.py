#!/usr/bin/env python3
"""Write the TEQUILA-seq snakemake_config.yaml for the epilepsy buccal-swab dataset.

Each sample gets one input per flowcell (the merged fastq.gz from step 1).
ESPRESSO treats multiple inputs with the same sample name as one sample, so
both flowcells are pooled per barcode at quantification time while alignments
stay separate (alignment/<sample>/<input index>/) for per-flowcell QC.
"""
import argparse
import csv
import os
import sys

TEMPLATE = """# Generated by TEQUILA_Epilepsy_Nasal/scripts/make_snakemake_config.py - do not edit by hand
# Resource allocation
guppy_threads: 1
guppy_mem_gb: 4
guppy_time_hr: 1
minimap2_threads: {threads}
minimap2_mem_gb: 48
minimap2_time_hr: 24
espresso_s_threads: {espresso_threads}
espresso_s_mem_gb: {espresso_mem}
espresso_s_time_hr: 48
espresso_c_threads: {espresso_threads}
espresso_c_mem_gb: {espresso_mem}
espresso_c_time_hr: 48
espresso_q_mem_gb: {espresso_mem}
espresso_q_time_hr: 48
visualize_mem_gb: 40
# Command options
use_annotated_junctions_with_minimap2: true
keep_espresso_c_temp: false
output_compatible_isoforms: true
# Visualization options (UCSC tracks; the gene figures come from 08_isoform_report.sh)
enable_visualization: false
visualization_path: '{visualization_path}'
vis_normalize_counts: false
vis_target_gene: ''
vis_minimum_count: 1
vis_descriptive_name: 'ESPRESSO'
# Reference files (already downloaded by 00_setup.sh, so no URLs are needed)
gtf_url: ''
gtf_name: '{gtf_name}'
fasta_url: ''
fasta_name: '{fasta_name}'
# Executable paths
guppy_bin_path: ''
conda_wrapper: '{conda_wrapper}'
espresso_path: '{espresso_path}'
# Input samples: reads are already basecalled (fastq_pass), so 'fastq' is used
samples:
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sample-sheet', required=True)
    parser.add_argument('--fastq-dir',
                        help='per-sample fastq dir: <fastq-dir>/<sample>/<flowcell>.fastq.gz')
    parser.add_argument('--flowcells', default='',
                        help='comma separated flowcell labels, e.g. FC3B,FC3C')
    parser.add_argument('--bam-dir',
                        help='use already aligned reads instead: <bam-dir>/<sample>.bam (one input per sample)')
    parser.add_argument('--skip-samples', default='',
                        help='comma separated sample ids to leave out (e.g. no reads)')
    parser.add_argument('--threads', type=int, default=8,
                        help='threads for minimap2 jobs (and ESPRESSO unless --espresso-threads)')
    parser.add_argument('--espresso-threads', type=int, help='threads for ESPRESSO S / C')
    parser.add_argument('--espresso-mem-gb', type=int, default=64,
                        help='memory for each ESPRESSO S / C / Q job')
    parser.add_argument('--code-dir', required=True)
    parser.add_argument('--gtf-name', required=True)
    parser.add_argument('--fasta-name', required=True)
    parser.add_argument('--min-reads', type=int, default=1,
                        help='skip a flowcell input with fewer reads than this')
    parser.add_argument('--read-counts',
                        help='fastq_read_counts.tsv from step 1 (optional)')
    parser.add_argument('--out', required=True)
    parser.add_argument('--conda-wrapper',
                        help='command that runs its arguments in the pipeline env '
                             '(default: <code-dir>/conda_wrapper)')
    parser.add_argument('--index-out',
                        help='write sample/input_index/flowcell table here')
    args = parser.parse_args()

    flowcells = [f for f in args.flowcells.split(',') if f]
    skip = set(x for x in args.skip_samples.split(',') if x)
    if bool(args.fastq_dir) == bool(args.bam_dir):
        sys.exit('give exactly one of --fastq-dir or --bam-dir')
    if args.fastq_dir and not flowcells:
        sys.exit('--fastq-dir needs --flowcells')
    read_counts = dict()
    if args.read_counts and os.path.exists(args.read_counts):
        with open(args.read_counts) as handle:
            for row in csv.DictReader(handle, delimiter='\t'):
                read_counts[(row['sample_id'], row['flowcell'])] = int(row['n_reads'])

    lines = [TEMPLATE.format(
        threads=args.threads,
        espresso_threads=args.espresso_threads or args.threads,
        espresso_mem=args.espresso_mem_gb,
        visualization_path=os.path.join(args.code_dir, 'visualization'),
        gtf_name=args.gtf_name,
        fasta_name=args.fasta_name,
        conda_wrapper=args.conda_wrapper or os.path.join(args.code_dir, 'conda_wrapper'),
        espresso_path=os.path.join(args.code_dir, 'ESPRESSO_alpha1.2.2'))]

    n_samples = 0
    index_rows = ['sample_id\tinput_index\tflowcell\tpath\n']
    with open(args.sample_sheet) as handle:
        for row in csv.DictReader(handle, delimiter='\t'):
            sample = row['sample_id']
            if sample in skip:
                print('NOTE: {} skipped as requested'.format(sample), file=sys.stderr)
                continue
            inputs = list()
            if args.bam_dir:
                bam = os.path.join(args.bam_dir, '{}.bam'.format(sample))
                if os.path.exists(bam):
                    inputs.append(('bam', 'aligned', bam))
                else:
                    print('WARNING: missing {}'.format(bam), file=sys.stderr)
            for fc in (flowcells if args.fastq_dir else []):
                fastq = os.path.join(args.fastq_dir, sample, '{}.fastq.gz'.format(fc))
                if not os.path.exists(fastq):
                    print('WARNING: missing {}'.format(fastq), file=sys.stderr)
                    continue
                n_reads = read_counts.get((sample, fc))
                if n_reads is not None and n_reads < args.min_reads:
                    print('WARNING: skipping {} {} ({} reads)'.format(
                        sample, fc, n_reads), file=sys.stderr)
                    continue
                inputs.append(('fastq', fc, fastq))
            if not inputs:
                print('WARNING: no input for {}; sample left out'.format(sample),
                      file=sys.stderr)
                continue
            n_samples += 1
            lines.append('  {}:\n'.format(sample))
            for i, (kind, fc, path) in enumerate(inputs):
                index_rows.append('{}\t{}\t{}\t{}\n'.format(sample, i, fc, path))
                lines.append('    # {}\n'.format(fc))
                lines.append("    - {}: '{}'\n".format(kind, path))

    if n_samples == 0:
        sys.exit('no samples with fastq input found')

    with open(args.out, 'w') as handle:
        handle.writelines(lines)
    if args.index_out:
        with open(args.index_out, 'w') as handle:
            handle.writelines(index_rows)
    print('wrote {} ({} samples)'.format(args.out, n_samples))


if __name__ == '__main__':
    main()
